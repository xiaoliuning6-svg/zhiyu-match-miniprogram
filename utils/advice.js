// 对方回复生成 + AI 军师建议（规则引擎，不联网、不调用模型）
// 口径：对方只回应、不替用户做决定；军师只给参谋，不代聊

function pick(arr, seed) {
  const i = Math.abs(seed) % arr.length;
  return arr[i];
}

function hashStr(s) {
  let h = 0;
  for (let i = 0; i < s.length; i += 1) {
    h = (h * 31 + s.charCodeAt(i)) | 0;
  }
  return h;
}

